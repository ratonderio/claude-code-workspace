"""Repository protocols.

Rules that make visibility hard to get wrong:

* Task/project/event reads that a person may trigger take a `viewer` and apply visibility
  inside the query. There is deliberately no "get any task by id" method.
* Anything that writes takes already-validated domain objects. Rules live in services.
"""

from __future__ import annotations

from datetime import datetime
from types import TracebackType
from typing import Protocol, Self

from family_hq.domain.enums import EventType, ProjectStatus
from family_hq.domain.events import ActivityEvent
from family_hq.domain.external_refs import ExternalRef
from family_hq.domain.people import Category, Person
from family_hq.domain.projects import Project
from family_hq.domain.tasks import Task, TaskQuery


class PersonRepository(Protocol):
    def add(self, person: Person) -> None: ...
    def update(self, person: Person) -> None: ...
    def get(self, person_id: str) -> Person | None: ...
    def get_by_discord_id(self, discord_user_id: str) -> Person | None: ...
    def get_by_name(self, name: str) -> Person | None: ...
    def list(self, *, active_only: bool = False) -> list[Person]: ...
    def count(self) -> int: ...


class CategoryRepository(Protocol):
    def add(self, category: Category) -> None: ...
    def update(self, category: Category) -> None: ...
    def get(self, category_id: str) -> Category | None: ...
    def get_by_name(self, name: str) -> Category | None: ...
    def list(self, *, active_only: bool = False) -> list[Category]: ...
    def count(self) -> int: ...


class ProjectRepository(Protocol):
    def add(self, project: Project) -> None: ...
    def update(self, project: Project) -> None: ...
    def get_visible(self, project_id: str, viewer: Person) -> Project | None: ...
    def find_visible_by_name(self, name: str, viewer: Person) -> list[Project]: ...
    def list_visible(
        self, viewer: Person, *, statuses: frozenset[ProjectStatus] | None = None
    ) -> list[Project]: ...


class TaskRepository(Protocol):
    def add(self, task: Task) -> None: ...

    def update(self, task: Task) -> Task:
        """Write all fields if the stored version equals task.version; returns the task with
        version+1. Raises ConflictError when the row changed underneath us."""
        ...

    def get_visible(self, task_id: str, viewer: Person) -> Task | None: ...
    def find_visible_by_prefix(self, prefix: str, viewer: Person, limit: int = 3) -> list[Task]: ...
    def list(self, query: TaskQuery, viewer: Person) -> list[Task]: ...


class EventRepository(Protocol):
    def add(self, event: ActivityEvent) -> ActivityEvent:
        """Append; returns the event with its assigned seq."""
        ...

    def list_visible(
        self,
        viewer: Person,
        *,
        task_id: str | None = None,
        project_id: str | None = None,
        after_seq: int | None = None,
        event_types: frozenset[EventType] | None = None,
        since: datetime | None = None,
        limit: int | None = None,
        newest_first: bool = False,
    ) -> list[ActivityEvent]: ...


class ExternalRefRepository(Protocol):
    """Integration bookkeeping. Not viewer-filtered: callers must already have obtained the
    entity through a visible path and applied SinkPolicy."""

    def get(
        self, entity_type: str, entity_id: str, system: str, ref_key: str
    ) -> ExternalRef | None: ...
    def upsert(self, ref: ExternalRef) -> None: ...
    def list_for_entity(self, entity_type: str, entity_id: str) -> list[ExternalRef]: ...


class UnitOfWork(Protocol):
    """One transaction. Leaving the block without commit() rolls back."""

    @property
    def people(self) -> PersonRepository: ...
    @property
    def categories(self) -> CategoryRepository: ...
    @property
    def projects(self) -> ProjectRepository: ...
    @property
    def tasks(self) -> TaskRepository: ...
    @property
    def events(self) -> EventRepository: ...
    @property
    def external_refs(self) -> ExternalRefRepository: ...

    def __enter__(self) -> Self: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
